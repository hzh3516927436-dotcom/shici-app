const outName = process.argv[2] || 'round01.json';
const LIMIT = parseInt(process.argv[3] || '40', 10);

// 排除已排队（fill-todo）与已完成（fill-done）轮次中的诗
const exclude = new Set();
for (const dir of ['fill-todo', 'fill-done']) {
    const dp = path.join(__dirname, dir);
    if (!fs.existsSync(dp)) continue;
    for (const f of fs.readdirSync(dp).filter(f => f.endsWith('.json'))) {
        if (f === outName) continue;
        try {
            const j = JSON.parse(fs.readFileSync(path.join(dp, f), 'utf8'));
            for (const p of (j.poems || [])) if (p.id) exclude.add(p.id);
            for (const it of (j.fills || [])) if (it.id) exclude.add(it.id);
        } catch (e) { }
    }
}

const all = [];
for (const f of fs.readdirSync(BULK).filter(f => f.startsWith('bulk_')).sort()) {
    for (const p of JSON.parse(fs.readFileSync(path.join(BULK, f), 'utf8')).poems) {
        all.push(p);
    }
}

const picked = [];
const used = new Set();
for (const entry of FAMOUS) {
    if (picked.length >= LIMIT) break;
    const [a, key] = entry.split('|');
    const hit = all.find(p =>
        !used.has(p.id) && !exclude.has(p.id) && p.author === a &&
        (p.background === undefined || p.background === '') &&
        (p.title === key || p.title.startsWith(key + '·') || p.title.startsWith(key + ' ') || p.title.startsWith(key + '（') || p.title.startsWith(key + ' 其'))
    );
    if (hit) { used.add(hit.id); picked.push(hit); }
}

